"""Lab 11: Assignment 2 -- Prove Test Independence With a Deliberate Bug
Introduces a deliberate bug into coding_agent (inverts filter logic: != instead of ==)
WITHOUT changing testing_agent.
Proves that independent acceptance-criteria tests catch regressions rather than blindly passing.
"""

def requirement_agent():
    return [{
        "id": "US-1",
        "acceptance_criteria": [
            "only filtered rows matching region 'North' must be present in output"
        ]
    }]

def buggy_coding_agent():
    """DELIBERATE BUG: inverted comparison ( != instead of == )"""
    def export_endpoint(rows, applied_filters, columns):
        # BUG: keeping rows that DO NOT match the filter!
        filtered = [r for r in rows if any(r.get(k) != v for k, v in applied_filters.items())]
        lines = [",".join(columns)]
        for r in filtered:
            lines.append(",".join(str(r.get(c, "")) for c in columns))
        return "\n".join(lines)
    return export_endpoint

def independent_testing_agent():
    """Independent test: derived only from acceptance criteria."""
    def test_suite(export_fn):
        rows = [
            {"region": "North", "sales": 100},
            {"region": "South", "sales": 200},
            {"region": "North", "sales": 150},
        ]
        columns = ["region", "sales"]
        csv_out = export_fn(rows, {"region": "North"}, columns)
        
        # Test checks that 'South' is NEVER present
        has_south = any("South" in line for line in csv_out.splitlines()[1:])
        has_north = any("North" in line for line in csv_out.splitlines()[1:])
        
        test_passed = (not has_south) and has_north
        return {
            "test_name": "verify_filter_exclusion",
            "passed": test_passed,
            "details": f"Generated CSV:\n{csv_out}",
            "failure_reason": "South rows leaked into filtered North export!" if not test_passed else None
        }
    return test_suite

if __name__ == "__main__":
    print("=== Testing Independent Verification Against Buggy Code ===")
    buggy_fn = buggy_coding_agent()
    test_suite = independent_testing_agent()
    result = test_suite(buggy_fn)

    print(f"Test Name:       {result['test_name']}")
    print(f"Status:          {'PASS' if result['passed'] else 'FAIL (Regression Caught!)'}")
    print(f"Failure Reason:  {result['failure_reason']}")
    print("\n=== Output Generated by Buggy Implementation ===")
    print(result['details'])

    assert result["passed"] is False, "Independent test must catch the inverted filter bug!"
    print("\nConfirmed: Independent test successfully rejected the faulty implementation.")
