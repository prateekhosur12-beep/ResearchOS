import React, { useEffect, useState } from "react";
import { api } from "../api";
import type { TabProps } from "../App";
import type { Draft } from "../types";
import { useAsync } from "../hooks";
import { Markdown } from "../markdown";
import {
  Badge,
  Button,
  Card,
  CardHeader,
  Divider,
  EmptyState,
  ErrorNote,
  Field,
  Modal,
  Note,
  Spinner,
  StatusPill,
  fmtTime,
} from "./ui";
import { IconDoc, IconDownload, IconExternal, IconSpinner } from "./icons";

export function DraftTab({ projectId, refreshKey, goTo }: TabProps) {
  const draftQ = useAsync(() => api.draft(projectId), [projectId, refreshKey]);
  const approvalsQ = useAsync(() => api.approvals(projectId), [projectId, refreshKey]);

  const draft: Draft | null = draftQ.data?.draft ?? draftQ.data ?? null;
  const hasDraft = !!draft?.markdown;
  const approvals = approvalsQ.data?.approvals ?? [];
  const pending = approvals.find((a: any) => a.status === "pending" && a.artifact_type === "draft");

  const [active, setActive] = useState<string | null>(null);
  const [editing, setEditing] = useState(false);
  const [buffer, setBuffer] = useState("");
  const [busy, setBusy] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [regenOpen, setRegenOpen] = useState(false);
  const [feedback, setFeedback] = useState("");

  const sections = draft?.sections ?? [];
  const current = sections.find((s) => s.name === active) ?? sections[0] ?? null;

  useEffect(() => {
    setEditing(false);
  }, [current?.name, draft?.version]);

  async function save() {
    if (!current) return;
    setBusy("save");
    setError(null);
    try {
      await api.editSection(projectId, current.name, buffer);
      setEditing(false);
      draftQ.reload();
      approvalsQ.reload();
    } catch (e: any) {
      setError(e?.message ?? String(e));
    } finally {
      setBusy(null);
    }
  }

  async function regenerate() {
    if (!current) return;
    setBusy("regen");
    setError(null);
    try {
      await api.regenerateSection(projectId, current.name, feedback.trim() || undefined);
      setRegenOpen(false);
      setFeedback("");
      draftQ.reload();
    } catch (e: any) {
      setError(e?.message ?? String(e));
    } finally {
      setBusy(null);
    }
  }

  async function decide(decision: "approved" | "rejected") {
    if (!pending) return;
    setBusy(decision);
    setError(null);
    try {
      await api.decide(pending.id, decision, decision === "approved" ? "Reviewed in the UI" : "Rejected in the UI");
      approvalsQ.reload();
      draftQ.reload();
    } catch (e: any) {
      setError(e?.message ?? String(e));
    } finally {
      setBusy(null);
    }
  }

  if (draftQ.loading && !draftQ.data) return <Spinner label="Loading draft…" />;
  if (draftQ.error) return <ErrorNote title="Could not load the draft">{draftQ.error}</ErrorNote>;

  if (!hasDraft) {
    return (
      <EmptyState
        icon={<IconDoc size={22} />}
        title="No draft yet"
        description="The drafting stage runs after gaps and ideas, using only the retrieved corpus. Enable “Generate draft” in the run settings and start a run."
        action={
          <Button variant="primary" size="sm" onClick={() => goTo("overview")}>
            Go to run panel
          </Button>
        }
      />
    );
  }

  const totalWords = sections.reduce((sum, s) => sum + (s.word_count ?? 0), 0);

  return (
    <div className="space-y-4">
      <Card>
        <CardHeader
          title={draft?.title ?? "Draft"}
          description={
            <span className="flex flex-wrap items-center gap-x-3 gap-y-1">
              <span>version {draft?.version}</span>
              <span>·</span>
              <span className="tabular-nums">{totalWords} words</span>
              <span>·</span>
              <span>{sections.length} sections</span>
              <span>·</span>
              <span>generated by {draft?.generated_by}</span>
              <span>·</span>
              <span>updated {fmtTime(draft?.updated_at)}</span>
            </span>
          }
          actions={
            <>
              <StatusPill status={draft?.status} />
              <Button variant="ghost" size="sm" onClick={() => { draftQ.reload(); approvalsQ.reload(); }}>
                Refresh
              </Button>
            </>
          }
        />

        {pending && (
          <div className="mb-3 flex flex-wrap items-center justify-between gap-2 rounded-md border border-primary-100 bg-primary-50/60 px-3 py-2">
            <span className="text-[13px] text-ink-700">
              Human approval pending — the run paused at the approval gate. Nothing is exported until you decide.
            </span>
            <span className="flex gap-2">
              <Button
                variant="primary"
                size="sm"
                loading={busy === "approved"}
                onClick={() => decide("approved")}
              >
                Approve draft
              </Button>
              <Button variant="danger" size="sm" loading={busy === "rejected"} onClick={() => decide("rejected")}>
                Reject
              </Button>
            </span>
          </div>
        )}

        {error && (
          <div className="mb-3">
            <ErrorNote>{error}</ErrorNote>
          </div>
        )}

        <div className="grid gap-4 lg:grid-cols-[220px_minmax(0,1fr)]">
          {/* sections nav */}
          <nav className="space-y-0.5 lg:border-r lg:border-slate-100 lg:pr-3">
            {sections.map((s) => {
              const isActive = current?.name === s.name;
              return (
                <button
                  key={s.name}
                  onClick={() => setActive(s.name)}
                  className={`flex w-full items-center justify-between gap-2 rounded-md px-2 py-1.5 text-left text-[13px] ${
                    isActive ? "bg-slate-100 font-medium text-ink-900" : "text-ink-600 hover:bg-slate-50"
                  }`}
                >
                  <span className="truncate">{s.name}</span>
                  <span className="shrink-0 text-2xs tabular-nums text-ink-400">{s.word_count ?? 0}</span>
                </button>
              );
            })}
          </nav>

          {/* content */}
          <div className="min-w-0">
            {current && (
              <>
                <div className="mb-2 flex items-center justify-between gap-2">
                  <div className="flex items-center gap-2">
                    <h3 className="text-[14px] font-semibold text-ink-900">{current.name}</h3>
                    {current.generated_by && <Badge tone="muted">{current.generated_by}</Badge>}
                  </div>
                  <div className="flex gap-1.5">
                    {editing ? (
                      <>
                        <Button variant="ghost" size="sm" onClick={() => setEditing(false)} disabled={busy === "save"}>
                          Cancel
                        </Button>
                        <Button
                          variant="primary"
                          size="sm"
                          onClick={save}
                          loading={busy === "save"}
                          disabled={buffer === current.markdown}
                        >
                          Save as new version
                        </Button>
                      </>
                    ) : (
                      <>
                        <Button
                          variant="secondary"
                          size="sm"
                          onClick={() => {
                            setBuffer(current.markdown);
                            setEditing(true);
                          }}
                        >
                          Edit
                        </Button>
                        <Button variant="secondary" size="sm" onClick={() => setRegenOpen(true)}>
                          Regenerate
                        </Button>
                      </>
                    )}
                  </div>
                </div>

                {editing ? (
                  <>
                    <textarea
                      className="textarea min-h-[420px] font-mono text-[12.5px] leading-6"
                      value={buffer}
                      onChange={(e) => setBuffer(e.target.value)}
                    />
                    <p className="mt-1 text-2xs text-ink-400">
                      Saving creates a new draft version; the previous text is kept in the version history.
                    </p>
                  </>
                ) : (
                  <div className="prose-doc min-h-[320px] rounded-md border border-slate-100 bg-white px-4 py-3">
                    <Markdown text={current.markdown} />
                  </div>
                )}

                {(current.citations?.length ?? 0) > 0 && (
                  <p className="mt-2 flex flex-wrap gap-1 text-2xs text-ink-400">
                    cites:{" "}
                    {(current.citations ?? []).map((c) => (
                      <span key={c} className="rounded bg-slate-100 px-1 font-mono text-ink-600">
                        {c}
                      </span>
                    ))}
                  </p>
                )}
              </>
            )}
          </div>
        </div>
      </Card>

      {draft?.bibliography?.length ? (
        <Card>
          <CardHeader
            title="Bibliography"
            description={`${draft.bibliography.length} entries · every entry resolves to a stored paper`}
            actions={
              <Button
                variant="ghost"
                size="sm"
                icon={<IconDownload size={13} />}
                onClick={async () => {
                  setBusy("bibtex");
                  try {
                    await api.createExport(projectId, "bibtex");
                    goTo("exports");
                  } catch (e: any) {
                    setError(e?.message ?? String(e));
                  } finally {
                    setBusy(null);
                  }
                }}
                loading={busy === "bibtex"}
              >
                Export BibTeX
              </Button>
            }
          />
          <div className="-mx-4 border-t border-slate-100">
            <table className="table-base">
              <thead>
                <tr>
                  <th className="w-16">Key</th>
                  <th>Title</th>
                  <th className="w-56">Authors</th>
                  <th className="w-16">Year</th>
                  <th className="w-20">DOI</th>
                </tr>
              </thead>
              <tbody>
                {draft.bibliography.map((b) => (
                  <tr key={b.key}>
                    <td className="font-mono text-2xs text-ink-500">{b.key}</td>
                    <td className="text-[13px]">{b.title}</td>
                    <td className="truncate text-2xs text-ink-500">
                      {(b.authors ?? []).slice(0, 3).map((a: any) => a.name ?? a.display_name).join(", ")}
                      {(b.authors?.length ?? 0) > 3 ? " et al." : ""}
                    </td>
                    <td className="tabular-nums text-[13px]">{b.year ?? "—"}</td>
                    <td className="text-2xs">
                      {b.doi ? (
                        <a
                          href={b.doi.startsWith("http") ? b.doi : `https://doi.org/${b.doi}`}
                          target="_blank"
                          rel="noreferrer"
                          className="inline-flex items-center gap-0.5 text-primary-700 hover:underline"
                        >
                          link <IconExternal size={10} />
                        </a>
                      ) : (
                        <span className="text-ink-300">—</span>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </Card>
      ) : null}

      <Modal
        open={regenOpen}
        onClose={() => setRegenOpen(false)}
        title={`Regenerate “${current?.name ?? ""}”`}
        description="The section is rewritten from the same stored evidence. Other sections are untouched."
        footer={
          <>
            <Button variant="ghost" onClick={() => setRegenOpen(false)} disabled={busy === "regen"}>
              Cancel
            </Button>
            <Button variant="primary" onClick={regenerate} loading={busy === "regen"}>
              Regenerate section
            </Button>
          </>
        }
      >
        <Field
          label="Feedback (optional)"
          hint="Steers the rewrite, e.g. “focus on datasets and limitations, keep it under 300 words”."
        >
          <textarea className="textarea min-h-[96px]" value={feedback} onChange={(e) => setFeedback(e.target.value)} />
        </Field>
        <div className="mt-3">
          <Note>
            Regeneration runs the drafting agent again with real evidence. If Ollama is offline, the deterministic
            template is used and the section is labelled as such.
          </Note>
        </div>
      </Modal>
    </div>
  );
}
